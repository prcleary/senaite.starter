# -*- coding: utf-8 -*-

from cgi import escape

from bika.lims import api
from Products.Archetypes.Registry import registerWidget
from senaite.core.browser.widgets import QuerySelectWidget


class CNICWidget(QuerySelectWidget):
    """Patient lookup by CNIC

    Same widget senaite.patient uses for the Medical Record Number
    (TemporaryIdentifierWidget), without temporary/autogenerated values: it
    searches existing patients and allows to enter a new value. The value is
    stored as a single string.
    """
    _properties = QuerySelectWidget._properties.copy()
    _properties.update({
        "multi_valued": False,
        "allow_user_value": True,
        # display the CNIC of the selected patient, not the patient's title
        "display_template": "${cnic}",
    })

    def process_form(self, instance, field, form, empty_marker=None,
                     emptyReturnsMarker=False, validating=True):
        """Returns the single value of the field
        """
        value = form.get(field.getName(), "")
        if isinstance(value, (list, tuple)):
            value = value and value[0] or ""
        if not api.is_string(value):
            value = ""
        # the textarea of the widget contains one value per line
        values = filter(None, map(lambda v: v.strip(), value.splitlines()))
        if not values:
            return None, {}
        return values[0], {}

    def get_render_data(self, context, field, reference, template):
        """Provides the data to render the display template
        """
        data = super(CNICWidget, self).get_render_data(
            context, field, reference, template)
        if data:
            data["cnic"] = reference
        return data

    def render_reference(self, context, field, reference):
        """Renders the CNIC in view mode, linked to the patient of the sample
        like senaite.patient renders the Medical Record Number
        """
        cnic = escape(api.to_utf8(reference, default=""), quote=True)
        if not cnic:
            return ""
        patient = None
        get_linked_patient = getattr(field, "get_linked_patient", None)
        if callable(get_linked_patient):
            patient = get_linked_patient(context)
        if patient is None:
            return cnic
        url = escape(api.get_url(patient), quote=True)
        return '<a href="{}">{}</a>'.format(url, cnic)


registerWidget(CNICWidget, title="CNICWidget")
