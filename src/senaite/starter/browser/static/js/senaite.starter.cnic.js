/**
 * senaite.starter: CNIC and Medical Record # (MRN) of samples
 *
 * Both fields are patient lookups. Picking a patient in one of them fills
 * the other one from the patient record:
 *
 * - MRN picked: senaite.patient fills the patient fields of the sample
 *   (senaite.patient: webpack/app/components/temporaryidentifierwidget.coffee)
 *   and this fills the CNIC. MRN removed: the CNIC is cleared, like the other
 *   patient fields.
 * - CNIC picked: the MRN of the patient with that CNIC is set, so that
 *   senaite.patient fills the other patient fields.
 *
 * Values are set like senaite.patient does: with the native setter of the
 * textarea of the widget plus an "input" event, which the ReactJS widget
 * handles as a new selection.
 */
(function () {
  "use strict";

  var MRN_FIELD = "MedicalRecordNumber";
  var CNIC_FIELD = "CNIC";
  // MRN placeholder of senaite.patient for temporary (autogenerated) MRNs
  var AUTO_WILDCARD = "-- autogenerated --";
  var PATIENT_CATALOG = "senaite_catalog_patient";

  // Textarea names: "<field>" in the sample view, "<field>-<n>" in the
  // sample add form (n is the column of the sample)
  var FIELD_NAME = /^(MedicalRecordNumber|CNIC)(-\d+)?$/;

  function get_portal_url() {
    var input = document.querySelector("input[name='portal_url']");
    return (input && input.value) || window.portal_url || "";
  }

  // Same rules as senaite.starter.api.format_cnic
  function format_cnic(value) {
    var cnic = (value || "").trim();
    var digits = cnic.replace(/[\s\-]/g, "");
    if (/^\d{13}$/.test(digits)) {
      return [digits.slice(0, 5), digits.slice(5, 12), digits.slice(12)].join("-");
    }
    return cnic;
  }

  function get_textarea(field, suffix) {
    return document.querySelector("textarea[name='" + field + suffix + "']");
  }

  // Set the value with the native setter, so the ReactJS widget notices it
  function set_value(input, value) {
    if (!input || input.value === value) {
      return;
    }
    var setter = Object.getOwnPropertyDescriptor(
      window.HTMLTextAreaElement.prototype, "value").set;
    setter.call(input, value);
    input.dispatchEvent(new Event("input", {bubbles: true}));
  }

  // Resolves with the patient found by the query or null. Same JSON API and
  // query senaite.patient uses to fetch the data of a selected patient
  function fetch_patient(query) {
    var catalog = document.querySelector("[name='config_catalog']");
    var params = new URLSearchParams();
    params.append("portal_type", "Patient");
    params.append("catalog_name", (catalog && catalog.value) || PATIENT_CATALOG);
    params.append("include_fields", "mrn,cnic");
    params.append("page_size", "1");
    Object.keys(query).forEach(function (key) {
      params.append(key, query[key]);
    });
    return fetch(get_portal_url() + "/@@API/read", {
      method: "POST",
      credentials: "same-origin",
      headers: {
        "Content-Type": "application/x-www-form-urlencoded; charset=UTF-8"
      },
      body: params.toString()
    }).then(function (response) {
      return response.ok ? response.json() : {};
    }).then(function (data) {
      var objects = (data && data.objects) || [];
      return objects.length ? objects[0] : null;
    });
  }

  function on_mrn_selected(suffix, mrn) {
    if (!mrn || mrn === AUTO_WILDCARD) {
      return;
    }
    fetch_patient({patient_mrn: mrn}).then(function (patient) {
      // keep the CNIC entered by the user for new patients
      if (!patient) {
        return;
      }
      set_value(get_textarea(CNIC_FIELD, suffix), format_cnic(patient.cnic));
    }).catch(log_error);
  }

  function on_mrn_deselected(suffix) {
    set_value(get_textarea(CNIC_FIELD, suffix), "");
  }

  function on_cnic_selected(suffix, value) {
    var cnic = format_cnic(value);
    if (!cnic) {
      return;
    }
    fetch_patient({patient_cnic: cnic}).then(function (patient) {
      // keep the MRN entered by the user for new patients
      if (!patient || !patient.mrn) {
        return;
      }
      var mrn = get_textarea(MRN_FIELD, suffix);
      if (!mrn || mrn.value === patient.mrn) {
        return;
      }
      // the patient is known, so the MRN is no longer temporary
      var temporary = document.getElementById(MRN_FIELD + suffix + "_temporary");
      if (temporary && temporary.checked) {
        temporary.checked = false;
        temporary.dispatchEvent(new Event("change", {bubbles: true}));
      }
      set_value(mrn, patient.mrn);
    }).catch(log_error);
  }

  function log_error(error) {
    console.error("[senaite.starter.cnic]", error);
  }

  // Custom events of the ReactJS widgets are fired on their textarea.
  // NOTE: browsers fire "select" also when text is selected in an input, but
  //       only the events of the widgets carry the selected value
  function get_event_info(event) {
    var target = event.target;
    var detail = event.detail;
    if (!target || !detail || typeof detail !== "object") {
      return null;
    }
    var match = FIELD_NAME.exec(target.getAttribute("name") || "");
    if (!match) {
      return null;
    }
    return {field: match[1], suffix: match[2] || "", value: detail.value};
  }

  function on_select(event) {
    var info = get_event_info(event);
    if (!info) {
      return;
    }
    if (info.field === MRN_FIELD) {
      on_mrn_selected(info.suffix, info.value);
    } else {
      on_cnic_selected(info.suffix, info.value);
    }
  }

  function on_deselect(event) {
    var info = get_event_info(event);
    if (info && info.field === MRN_FIELD) {
      on_mrn_deselected(info.suffix);
    }
  }

  function init() {
    document.body.addEventListener("select", on_select);
    document.body.addEventListener("deselect", on_deselect);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
}());
