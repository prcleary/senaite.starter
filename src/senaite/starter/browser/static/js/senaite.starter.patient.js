/**
 * senaite.starter: patient fields of samples
 *
 * Fills the patient fields of this add-on in the sample add form and in the
 * sample view. senaite.patient fills first and last name, place of residence,
 * date of birth, sex and gender
 * (senaite.patient: webpack/app/components/temporaryidentifierwidget.coffee):
 *
 * - MRN picked: CNIC, middle name, email and phone are filled from the
 *   patient record. MRN removed: they are cleared, like senaite.patient's.
 * - CNIC picked: the MRN of the patient with that CNIC is set, so that all
 *   patient fields are filled from the patient record.
 * - "Copy to new": the copied MRNs are picked again, so that the patient
 *   fields are refreshed from the patient records. The patient values of new
 *   samples replace those of the patient (see senaite.starter.sync).
 *
 * Values are set like senaite.patient does: with the native value setter
 * plus an "input" event, which ReactJS widgets handle as a new selection.
 */
(function () {
  "use strict";

  var MRN_FIELD = "MedicalRecordNumber";
  var CNIC_FIELD = "CNIC";
  // MRN placeholder of senaite.patient for temporary (autogenerated) MRNs
  var AUTO_WILDCARD = "-- autogenerated --";
  var PATIENT_CATALOG = "senaite_catalog_patient";

  // Sample fields filled by this script: field name, subfield of record
  // fields (e.g. "PatientFullName-0.middlename:ignore_empty:record") and the
  // name of the patient field
  var PATIENT_FIELDS = [
    {name: CNIC_FIELD, subfield: "", key: "cnic"},
    {name: "PatientFullName", subfield: "middlename", key: "middlename"},
    {name: "PatientEmail", subfield: "", key: "email"},
    {name: "PatientPhone", subfield: "", key: "phone"}
  ];

  // Textarea names of the lookups: "<field>" in the sample view,
  // "<field>-<n>" in the sample add form (n is the column of the sample)
  var FIELD_NAME = /^(MedicalRecordNumber|CNIC)(-\d+)?$/;

  function get_portal_url() {
    var input = document.querySelector("input[name='portal_url']");
    return (input && input.value) || window.portal_url || "";
  }

  // Values are used as entered, like senaite.starter.api.to_cnic
  function to_value(value) {
    if (value === null || value === undefined) {
      return "";
    }
    return String(value).trim();
  }

  function get_textarea(field, suffix) {
    return document.querySelector("textarea[name='" + field + suffix + "']");
  }

  function get_input(field, suffix) {
    if (field.name === CNIC_FIELD) {
      return get_textarea(CNIC_FIELD, suffix);
    }
    var name = field.name + suffix;
    if (field.subfield) {
      name = name + "." + field.subfield + ":";
      return document.querySelector("input[name^='" + name + "']");
    }
    return document.querySelector("input[name='" + name + "']");
  }

  // Set the value with the native setter, so that ReactJS widgets notice it
  function set_value(input, value) {
    if (!input || input.value === value) {
      return;
    }
    var proto = window.HTMLInputElement.prototype;
    if (input.tagName === "TEXTAREA") {
      proto = window.HTMLTextAreaElement.prototype;
    }
    var setter = Object.getOwnPropertyDescriptor(proto, "value").set;
    setter.call(input, value);
    input.dispatchEvent(new Event("input", {bubbles: true}));
  }

  // Resolves with the patient found by the query or null. Same JSON API and
  // query senaite.patient uses to fetch the data of a selected patient
  function fetch_patient(query) {
    var catalog = document.querySelector("[name='config_catalog']");
    var fields = ["mrn"].concat(PATIENT_FIELDS.map(function (field) {
      return field.key;
    }));
    var params = new URLSearchParams();
    params.append("portal_type", "Patient");
    params.append("catalog_name", (catalog && catalog.value) || PATIENT_CATALOG);
    params.append("include_fields", fields.join(","));
    params.append("page_size", "1");
    Object.keys(query).forEach(function (key) {
      params.append(key, query[key]);
    });
    return fetch(get_portal_url() + "/@@API/read", {
      method: "POST",
      credentials: "same-origin",
      headers: {
        "Content-Type": "application/x-www-form-urlencoded; charset=UTF-8"
      },
      body: params.toString()
    }).then(function (response) {
      return response.ok ? response.json() : {};
    }).then(function (data) {
      var objects = (data && data.objects) || [];
      return objects.length ? objects[0] : null;
    });
  }

  function set_patient_fields(suffix, patient) {
    PATIENT_FIELDS.forEach(function (field) {
      var value = patient ? to_value(patient[field.key]) : "";
      set_value(get_input(field, suffix), value);
    });
  }

  function on_mrn_selected(suffix, mrn) {
    if (!mrn || mrn === AUTO_WILDCARD) {
      return;
    }
    fetch_patient({patient_mrn: mrn}).then(function (patient) {
      // keep the values entered by the user for new patients
      if (!patient) {
        return;
      }
      set_patient_fields(suffix, patient);
    }).catch(log_error);
  }

  function on_mrn_deselected(suffix) {
    set_patient_fields(suffix, null);
  }

  function on_cnic_selected(suffix, value) {
    var cnic = to_value(value);
    if (!cnic) {
      return;
    }
    fetch_patient({patient_cnic: cnic}).then(function (patient) {
      // keep the MRN entered by the user for new patients
      if (!patient || !patient.mrn) {
        return;
      }
      var mrn = get_textarea(MRN_FIELD, suffix);
      if (!mrn || mrn.value === patient.mrn) {
        return;
      }
      // the patient is known, so the MRN is no longer temporary
      var temporary = document.getElementById(MRN_FIELD + suffix + "_temporary");
      if (temporary && temporary.checked) {
        temporary.checked = false;
        temporary.dispatchEvent(new Event("change", {bubbles: true}));
      }
      set_value(mrn, patient.mrn);
    }).catch(log_error);
  }

  // Picks the copied MRNs again: the MRN widgets fire "select" events for
  // changed values only, so the event is fired here
  function reselect_copied_patients(attempts) {
    var textareas = document.querySelectorAll(
      "textarea[name^='" + MRN_FIELD + "-']");
    if (!textareas.length) {
      // the widgets are rendered by ReactJS after the page is loaded
      if (attempts > 0) {
        window.setTimeout(function () {
          reselect_copied_patients(attempts - 1);
        }, 200);
      }
      return;
    }
    Array.prototype.forEach.call(textareas, function (textarea) {
      var match = FIELD_NAME.exec(textarea.getAttribute("name") || "");
      if (!match || match[1] !== MRN_FIELD) {
        return;
      }
      var mrn = to_value(textarea.value.split("\n")[0]);
      if (!mrn || mrn === AUTO_WILDCARD) {
        return;
      }
      textarea.dispatchEvent(new CustomEvent("select", {
        detail: {value: mrn},
        bubbles: true
      }));
    });
  }

  // Sample add form opened with "Copy to new"
  function is_copy_form() {
    return document.body.classList.contains("template-ar_add") &&
      /[?&]copy_from=[^&]/.test(window.location.search);
  }

  function log_error(error) {
    console.error("[senaite.starter.patient]", error);
  }

  // Custom events of the ReactJS widgets are fired on their textarea.
  // NOTE: browsers fire "select" also when text is selected in an input, but
  //       only the events of the widgets carry the selected value
  function get_event_info(event) {
    var target = event.target;
    var detail = event.detail;
    if (!target || !detail || typeof detail !== "object") {
      return null;
    }
    var match = FIELD_NAME.exec(target.getAttribute("name") || "");
    if (!match) {
      return null;
    }
    return {field: match[1], suffix: match[2] || "", value: detail.value};
  }

  function on_select(event) {
    var info = get_event_info(event);
    if (!info) {
      return;
    }
    if (info.field === MRN_FIELD) {
      on_mrn_selected(info.suffix, info.value);
    } else {
      on_cnic_selected(info.suffix, info.value);
    }
  }

  function on_deselect(event) {
    var info = get_event_info(event);
    if (info && info.field === MRN_FIELD) {
      on_mrn_deselected(info.suffix);
    }
  }

  function init() {
    document.body.addEventListener("select", on_select);
    document.body.addEventListener("deselect", on_deselect);
  }

  // after all scripts are initialised, so that senaite.patient handles the
  // events fired for the copied MRNs as well
  function on_load() {
    if (is_copy_form()) {
      reselect_copied_patients(50);
    }
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
  if (document.readyState === "complete") {
    on_load();
  } else {
    window.addEventListener("load", on_load);
  }
}());
